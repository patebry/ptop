/// JS String.slice(0, n) counts UTF-16 units, including split surrogate pairs.
pub fn slice_units(input: &str, length: usize) -> String {
    String::from_utf16_lossy(&input.encode_utf16().take(length).collect::<Vec<_>>())
}

pub fn normalize(input: &str) -> String {
    let mut output = String::with_capacity(input.len());
    let mut chars = input.chars().peekable();
    while let Some(ch) = chars.next() {
        match ch {
            '\x00'..='\x08' | '\x0b'..='\x0c' | '\x0e'..='\x1a' | '\x1c'..='\x1f' | '\x7f' => {
                continue
            }
            '\r' => {
                if chars.peek() == Some(&'\n') {
                    chars.next();
                }
                output.push('\n');
            }
            '\t' => output.push_str("    "),
            '\x1b' => {
                let rest: String = chars.clone().collect();
                let valid = rest.strip_prefix('[').is_some_and(|s| {
                    s.trim_start_matches(|c: char| c.is_ascii_digit() || c == ';')
                        .starts_with('m')
                });
                if valid {
                    output.push(ch);
                }
            }
            _ => {
                let code = ch as u32;
                let index = REPLACEMENTS.partition_point(|(_, end, _)| *end < code);
                if let Some(&(start, _, replacement)) = REPLACEMENTS
                    .get(index)
                    .filter(|(start, _, _)| *start <= code)
                {
                    let _ = start;
                    output.push_str(replacement);
                } else {
                    output.push(ch);
                }
            }
        }
    }
    output
}
